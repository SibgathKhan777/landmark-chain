"""Write RECORDING_PLAN.md: a plan for the 60-second video of the live two-window call, timed from the saved results of a real run.

The call runs by itself (the scripted call takes about half a minute), so the plan is: narrate BEFORE it, let it play with no
narration (the stage page shows the English meaning of every turn), then narrate AFTER it.

Rules the plan keeps (a test enforces them):
  * the whole video fits in 60 seconds with at least MIN_SLACK seconds to spare;
  * the narrator never talks while the call plays;
  * the plan lists every turn of the saved run with what the viewer will see, taken from the result file;
  * the narration contains none of the phrases listed in FORBIDDEN.

Narration length is an ESTIMATE (WORDS_PER_SECOND), and the call length is estimated from the saved run's timings, which vary from run
to run. Time the first rehearsal and adjust.

    python live_call.py --run      # writes out/live/results.json
    python build_recording_plan.py
"""
import json
import re

import gnani

OUT = gnani.HERE / "out" / "live"
WORDS_PER_SECOND = 2.5          # about 150 words a minute, a calm reading pace. An estimate, not a measurement
GAP = 0.4                       # pause between shots
LIMIT = 60.0
MIN_SLACK = 3.0
RING, ANSWER_WAIT, TURN_GAP, TAIL = 1.6, 0.8, 0.9, 0.6      # the same pacing live_call.play_script uses

# Phrases that must never appear in the narration (see "What not to claim" in the plan).
FORBIDDEN = ["real-time", "real time", "live call", "on a real phone", "accurate", "accuracy", "ai translation", "translates any",
             "translates everything", "fluent", "customers use", "companies use", "solves", "%", "best", "first", "only one", "guarantee",
             "instant", "no delay", "under a second", "streaming"]

SHOTS = [
    dict(name="Hook", page="The stage page, before the call. Both windows are idle and the badges at the top are visible", do="hold still; do not press Play yet", kind="vo",
         say="A customer speaks Hindi. The biker hears Kannada. Each window only hears its own language."),
    dict(name="The call", page="Press Play scripted call, then keep the whole stage in frame: both windows and the middle panel",
         do="press Play scripted call and say nothing until the biker's window shows Call ended", kind="call", say=None),
    dict(name="What it can and cannot do", page="Scroll down so the turn log is in frame (it lists every turn and its result)",
         do="scroll down slowly after the call ends", kind="vo",
         say="Landmarks and a few set directions only. Anything else, it says so out loud."),
    dict(name="Close", page="Stay on the log. Keep the badges or the footer in frame if you can", do="hold the shot", kind="vo",
         say="Built on Gnani Prisma and Timbre. Synthetic voices. Kannada awaiting native review."),
]


def words(text):
    return len(re.findall(r"\S+", text))


def call_seconds(res):
    """How long the scripted call runs on screen, from the saved timings (the real pacing varies by a second or two)."""
    t = RING + ANSWER_WAIT + TAIL
    for turn in res["turns"]:
        t += turn["audio_s"] + turn["ms"]["total"] / 1000 + turn["play_s"] + TURN_GAP
    return t


def build_timeline(res):
    """Returns (rows, total_seconds). Each row is one shot with its start time and length."""
    rows, t = [], 0.0
    for i, shot in enumerate(SHOTS, 1):
        if shot["kind"] == "call":
            row = dict(shot=i, kind="call", seconds=call_seconds(res), text=None)
        else:
            row = dict(shot=i, kind="vo", text=shot["say"], seconds=words(shot["say"]) / WORDS_PER_SECOND)
        row["start"] = t
        rows.append(row)
        t += row["seconds"] + GAP
    return rows, t - GAP


def mmss(x):
    return f"{int(x // 60)}:{x % 60:04.1f}"


STATUS = {"translated": "translated", "partial": "partly translated", "untranslated": "refused out loud", "silent": "heard nothing"}
WHO = {"customer": "Customer", "biker": "Biker"}


