def load(path):
    return json.loads((OUT / path).read_text(encoding="utf-8")) if (OUT / path).exists() else None


if __name__ == "__main__":
    res = load("results.json")
    if res is None:
        raise SystemExit("Run `python live_call.py --run` first.")
    text = render(res, load("results_bike10.json"))
    (gnani.HERE / "RECORDING_PLAN.md").write_text(text, encoding="utf-8")
    rows, total = build_timeline(res)
    print(f"wrote RECORDING_PLAN.md: {total:.1f} s planned of {LIMIT:.0f} s ({LIMIT - total:.1f} s slack)")
