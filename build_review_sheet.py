"""Write kannada_review.md: every Kannada string the translator can speak, with its meaning, for a native speaker to check.

The Kannada tables were drafted without a native-speaker review. In a clean-audio check, Timbre could speak them and Prisma
could recognise them again, which shows they are pronounceable but not that they sound natural.

    python build_review_sheet.py
"""
import directions as D
import translate as T
from gnani import HERE

EXAMPLES = [("भैया ये गेट दूसरा गेट दायीं तरफ वाला", "hi-IN", "kn-IN"), ("मंदिर के पीछे नीला गेट", "hi-IN", "kn-IN"),
            ("पानी की टंकी के पास पीला मकान", "hi-IN", "kn-IN"), ("दूसरी गली में हरा मकान", "hi-IN", "kn-IN"),
            ("बाएं तरफ पहली दुकान", "hi-IN", "kn-IN"), ("हनुमान मंदिर के सामने हरा गेट", "hi-IN", "kn-IN"),
            ("बैंक के ऊपर सफेद मकान", "hi-IN", "kn-IN"), ("पेड़ के नीचे", "hi-IN", "kn-IN")]


def table(header, rows):
    line = lambda c: "| " + " | ".join(c) + " |"
    return "\n".join([line(header), line(["---"] * len(header))] + [line(r) for r in rows])


def clause_rows():
    np = {"colour": set(), "ordinal": set(), "target": {"BUILDING"}, "anchor": set(), "relation": set(), "side": set()}
    clauses = [("come straight", {"act": "STRAIGHT", "verb": "come"}), ("go straight", {"act": "STRAIGHT", "verb": "go"}),
               ("turn right", {"act": "TURN", "side": "RIGHT"}), ("turn left", {"act": "TURN", "side": "LEFT"}),
               ("you will see a building ahead", {"act": "SEE_AHEAD", "slots": np}), ("wait there", {"act": "WAIT", "place": "THERE"}),
               ("wait here", {"act": "WAIT", "place": "HERE"}), ("wait", {"act": "WAIT", "place": None}),
               ("I am coming", {"act": "COMING"}), ("I am standing here", {"act": "STANDING", "place": "HERE"}),
               ("I am standing", {"act": "STANDING", "place": None}), ("I can see the building", {"act": "SEEN", "slots": np})]
    return [[meaning, D.render(c, "kn-IN"), D.render(c, "hi-IN")] for meaning, c in clauses]


def build():
    parts = ["# Kannada review sheet", "",
             "This is every Kannada string the interpreter can speak, with its meaning in English. The wording was drafted from word "
             "tables **without a native-speaker review**. Please mark anything that is wrong, unnatural or rude, and say what a "
             "native speaker would say instead. Generated by `python build_review_sheet.py`; do not edit by hand.", ""]
    parts += ["## Landmark types (genitive form, as used before 'behind', 'near'...)", "",
              table(["Meaning", "Kannada"], [[T.EN_ANCHOR[k], v] for k, v in T.KN_ANCHOR.items()] + [["Hanuman temple", "ಹನುಮಾನ್ ದೇವಸ್ಥಾನದ"]]), ""]
    parts += ["## Relations", "", table(["Meaning", "Used alone", "Used before a noun"],
              [[k.lower().replace("_", " "), T.KN_REL_ADV[k], T.KN_REL_ADJ[k]] for k in T.KN_REL_ADV]), ""]
    parts += ["## Colours, numbers, sides, things", "",
              table(["Meaning", "Kannada"], [[k.lower(), v] for k, v in T.KN_COLOUR.items()]
                    + [[T.EN_ORD[k], v] for k, v in T.KN_ORD.items()]
                    + [[f"{k.lower()} (alone / before a noun)", f"{T.KN_SIDE_ADV[k]} / {T.KN_SIDE_ADJ[k]}"] for k in T.KN_SIDE_ADV]
                    + [[T.EN_TARGET[k], v] for k, v in T.KN_TARGET.items()] + [["of the lane", T.KN_LANE_GEN]]), ""]
    parts += ["## Directions and plans", "",
              "What the interpreter says for the instructions in a call. The Hindi column is what the customer hears when the biker says "
              "the same thing in Kannada. Hindi uses the polite plural 'वे' for the biker's own statements, because the interpreter does "
              "not know the speaker's gender. Please check both columns.", "",
              table(["Meaning", "Kannada", "Hindi"], clause_rows()), "",
              "Kannada the interpreter *understands* from the biker (only these three statements; it cannot parse Kannada directions): "
              + ", ".join(f"`{w}`" for w in sorted(D.K_COMING | D.K_STAND | D.K_SEEN)) + ". Only `ಬರುತ್ತಿದ್ದೇನೆ`, `ಕಾಣಿಸಿತು` and `ನಿಂತಿದ್ದೇನೆ` were checked against real Prisma output (clean and with bike noise); the other spellings "
              "are guesses at what Prisma may write for spoken variants. If a real rider says these another way, they are refused out loud.", ""]
    parts += ["## Set phrases", "", table(["Meaning", "Kannada"], [[T.INTENT_TEXT["en"][k], v] for k, v in T.INTENT_TEXT["kn-IN"].items()]), ""]
    parts += ["## Spoken notices", "",
              table(["When", "Kannada"], [["To the biker when the customer's message could not be translated", T.NOTICE["kn-IN"]["listener"]],
                                          ["To the biker after a partial translation", T.NOTICE["kn-IN"]["partial"]],
                                          ["To the biker when his own message could not be translated", T.NOTICE["kn-IN"]["speaker"]]]), ""]
    rows = []
    for text, src, dst in EXAMPLES:
        r = T.translate(text, src, dst)
        rows.append([text, r.output, r.english])
    parts += ["## Whole phrases the tables produce", "", table(["Hindi said", "Kannada spoken", "Meaning"], rows), ""]
    return "\n".join(parts)


if __name__ == "__main__":
    (HERE / "kannada_review.md").write_text(build(), encoding="utf-8")
    print("wrote kannada_review.md")
